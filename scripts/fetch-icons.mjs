import fs from 'node:fs/promises';
import path from 'node:path';

const OUT = path.join(process.cwd(), 'public', 'js', 'icons.js');
const names = [
  'file', 'file-text', 'file-code', 'braces', 'file-plus', 'file-plus-2', 'file-x',
  'folder', 'folder-open', 'folder-plus', 'folder-tree', 'folder-closed', 'folder-symlink',
  'save', 'search', 'replace', 'replace-all', 'refresh-cw', 'trash-2', 'pencil', 'copy', 'check',
  'git-compare', 'git-compare-arrows', 'arrow-left-right', 'arrow-left', 'arrow-right',
  'arrow-down', 'arrow-up', 'chevron-right', 'chevron-down', 'chevron-left', 'chevron-up',
  'chevrons-up-down', 'x', 'plus', 'minus', 'more-horizontal', 'settings', 'sun', 'moon',
  'monitor', 'panel-left', 'panel-left-close', 'panel-right', 'alert-triangle', 'info',
  'external-link', 'download', 'upload', 'wrap-text', 'type', 'case-sensitive', 'whole-word',
  'regex', 'rotate-ccw', 'rotate-cw', 'scissors', 'clipboard', 'list', 'command', 'keyboard',
  'eye', 'eye-off', 'square', 'columns-2', 'rows-2', 'maximize-2', 'circle', 'dot', 'sparkles',
  'file-diff', 'files', 'terminal', 'rocket', 'book-open', 'split-square-horizontal',
  'panel-top', 'layout-panel-left', 'filter', 'case-upper', 'case-lower', 'indent',
  'align-left', 'text-cursor-input', 'mouse-pointer-click', 'laptop', 'hard-drive',
  'circle-check', 'circle-x', 'circle-alert', 'loader-circle', 'clock', 'history',
  'file-search', 'folder-search', 'corner-down-left', 'equal', 'diff', 'merge',
];

const wanted = [...new Set(names)];
const found = {};
const missing = [];
for (const name of wanted) {
  const url = `https://unpkg.com/lucide-static@0.544.0/icons/${name}.svg`;
  try {
    const res = await fetch(url);
    if (!res.ok) {
      missing.push(name);
      continue;
    }
    let svg = await res.text();
    const inner = svg
      .replace(/^[\s\S]*?<svg[^>]*>/, '')
      .replace(/<\/svg>[\s\S]*$/, '')
      .replace(/\s+/g, ' ')
      .trim();
    found[name] = inner;
  } catch {
    missing.push(name);
  }
}

const body = Object.entries(found)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n');

const js = `// Auto-generated by scripts/fetch-icons.mjs — Lucide icons (ISC)
export const ICONS = {
${body}
};

const cache = new Map();

export function iconSVG(name, cls = '') {
  const key = name + '|' + cls;
  if (cache.has(key)) return cache.get(key);
  const body = ICONS[name] || ICONS['circle'] || '';
  const html = \`<svg class="icon \${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${body}</svg>\`;
  cache.set(key, html);
  return html;
}

export function iconEl(name, cls = '') {
  const span = document.createElement('span');
  span.className = 'icon-wrap';
  span.innerHTML = iconSVG(name, cls);
  return span.firstChild;
}
`;

await fs.mkdir(path.dirname(OUT), { recursive: true });
await fs.writeFile(OUT, js, 'utf8');
console.log(`icons: ${Object.keys(found).length} written, ${missing.length} missing`);
if (missing.length) console.log('missing:', missing.join(', '));
